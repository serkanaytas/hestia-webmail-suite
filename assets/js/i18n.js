function applyDomTranslations() {
  // Update elements with data-i18n
  // Update elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const translated = t(key);
    if (translated && translated !== key) {
      el.textContent = translated;
    }
  });

  // Update elements with data-i18n-html
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    const translated = t(key);
    if (translated && translated !== key) {
      el.innerHTML = translated;
    }
  });

  // Update placeholders
  document.querySelectorAll('[data-i18n-placeholder], [data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder') || el.getAttribute('data-i18n-ph');
    const translated = t(key);
    if (translated && translated !== key) {
      el.placeholder = translated;
    }
  });

  // Update titles
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    const translated = t(key);
    if (translated && translated !== key) {
      el.title = translated;
    }
  });

  // Update top button code text and flag icon
  const flagHtml = getLangFlagIconHtml(currentLang);
  document.querySelectorAll('.current-lang-flag').forEach(el => {
    el.innerHTML = flagHtml;
  });
  document.querySelectorAll('.current-lang-code-text').forEach(el => {
    el.textContent = currentLang.toUpperCase();
  });

  // Update active state in dropdown menus
  document.querySelectorAll('.lang-item').forEach(item => {
    if (item.getAttribute('data-lang') === currentLang) {
      item.classList.add('active');
    } else {
      item.classList.remove('active');
    }
  });

  // Update settings card options if present
  document.querySelectorAll('.lang-card-option').forEach(card => {
    const cLang = card.getAttribute('data-lang') || card.id.replace('lang-opt-', '');
    if (cLang === currentLang) {
      card.classList.add('active');
    } else {
      card.classList.remove('active');
    }
  });
}

function setLanguage(lang, persist = true) {
  if (!lang) lang = 'tr';
  currentLang = lang;
  localStorage.setItem('hestia_lang', lang);
  document.documentElement.setAttribute('lang', lang);

  // If this language is not yet in I18N_TRANSLATIONS, fetch it dynamically from API
  if (!I18N_TRANSLATIONS[lang]) {
    fetch('api.php?action=language_get&code=' + encodeURIComponent(lang))
      .then(r => r.json())
      .then(res => {
        if (res.success && res.data && res.data.translations) {
          I18N_TRANSLATIONS[lang] = res.data.translations;
        }
        applyDomTranslations();
      })
      .catch(() => {
        applyDomTranslations();
      });
  } else {
    applyDomTranslations();
  }

  if (persist) {
    const fd = new FormData();
    fd.append('action', 'save_language');
    fd.append('lang', lang);
    fetch('api.php', { method: 'POST', body: fd }).catch(() => {});

    if (typeof showToast === 'function') {
      const msg = t('lang_changed_toast', 'Dil güncellendi.');
      showToast(msg, 'info');
    }
  }
}

function syncInstalledLanguagesToMenus() {
  fetch('api.php?action=languages_list')
    .then(r => r.json())
    .then(res => {
      if (res.success && Array.isArray(res.data) && res.data.length > 0) {
        installedLanguagesCache = res.data;
        renderLanguageMenus(res.data);
      }
    })
    .catch(() => {});
}

function renderLanguageMenus(langs) {
  // Update Top Navbar & Login Screen dropdown menus
  const menuIds = ['lang-dropdown-menu', 'login-lang-dropdown-menu'];
  menuIds.forEach(id => {
    const menuEl = document.getElementById(id);
    if (!menuEl) return;
    menuEl.innerHTML = langs.map(l => {
      const isActive = l.code === currentLang ? ' active' : '';
      const flagSvg = getLangFlagIconHtml(l.code);
      const name = t('lang_' + l.code, l.name);
      return `<a href="javascript:void(0)" class="lang-item${isActive}" data-lang="${l.code}" onclick="setLanguage('${l.code}')">
        <span class="lang-flag-svg">${flagSvg}</span>
        <span style="font-weight:600;">${name}</span>
        <svg class="lang-item-check" width="12" height="12" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="3"><polyline points="20 6 9 17 4 12"/></svg>
      </a>`;
    }).join('');
  });

  // Update Settings -> Appearance Language Grid if present
  const gridEl = document.querySelector('.lang-settings-grid');
  if (gridEl) {
    gridEl.innerHTML = langs.map(l => {
      const isActive = l.code === currentLang ? ' active' : '';
      const flagSvg = getLangFlagIconHtml(l.code);
      const name = t('lang_' + l.code, l.name);
      const descKey = 'lang_' + l.code + '_desc';
      const desc = t(descKey, (l.is_default ? t('lang_default_desc', 'Varsayılan dil') : l.code.toUpperCase()));
      return `<div class="lang-card-option${isActive}" id="lang-opt-${l.code}" data-lang="${l.code}" onclick="setLanguage('${l.code}')">
        <span class="lang-flag-svg" style="transform:scale(1.25);margin-right:4px;">${flagSvg}</span>
        <div style="flex:1;">
          <div style="font-weight:700;font-size:0.9rem;">${name}</div>
          <div style="font-size:0.75rem;color:var(--text-muted);">${desc}</div>
        </div>
        <div class="lang-badge-check">
          <svg width="11" height="11" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="3.5"><polyline points="20 6 9 17 4 12"/></svg>
        </div>
      </div>`;
    }).join('');
  }
}

