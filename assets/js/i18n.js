function t(key, fallback = '') {
  if (I18N_TRANSLATIONS[currentLang] && I18N_TRANSLATIONS[currentLang][key] !== undefined) {
    return I18N_TRANSLATIONS[currentLang][key];
  }
  if (I18N_TRANSLATIONS['tr'] && I18N_TRANSLATIONS['tr'][key] !== undefined) {
    return I18N_TRANSLATIONS['tr'][key];
  }
  return fallback || key;
}

